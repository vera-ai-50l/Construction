// Is this product vibe-coded, or professionally designed?
//
// Three layers, strongest first:
// 1. Build fingerprints: what AI app builders leave in a site's address, HTML and JS
//    bundles (lovable.app/base44.app/bolt.host/replit.app hosts, "lovable-uploads",
//    gpt-engineer tags, @base44/sdk, untouched Vite template titles). Sources: builder
//    docs summarised by AXON Build (2026) and AIWebsiteDetector's Lovable guide.
// 2. Default-design patterns, measured from computed styles in a real browser
//    (after Adrian Krebs, "Scoring Show HN submissions for AI design patterns", 2026):
//    Inter/Geist everywhere, gradient headline text, purple-indigo accents, pill badge
//    above the hero, colored glows, colored card borders, glassmorphism, emoji icons,
//    identical icon cards, low-contrast dark mode.
// 3. Polish signals: evidence that money went into design (a Framer or Webflow
//    marketing site, a custom typeface, design job openings, a bigger funded team).
//    These count against a lead: a polished product needs us less.
import * as cheerio from 'cheerio';
import { getText } from '../http.mjs';

const BUILDER_HOSTS = [
  ['lovable', /(^|\.)lovable\.app$|(^|\.)lovableproject\.com$/],
  ['base44', /(^|\.)base44\.app$/],
  ['bolt', /(^|\.)bolt\.host$/],
  ['replit', /(^|\.)replit\.app$|(^|\.)repl\.co$/],
  ['v0', /(^|\.)v0\.app$|(^|\.)vusercontent\.net$/],
];

const BUILDER_CODE = [
  ['lovable', /lovable-uploads|gpt-engineer|gptengineer|lovable-tagger|data-lovable|cdn\.gpteng\.co|lovable\.dev\/opengraph|Edit with Lovable|lovableproject\.com/i],
  ['base44', /@base44\/sdk|base44\.app|base44-app|Made with Base44/i],
  ['bolt', /bolt\.new|bolt\.host|Made in Bolt|stackblitz\.io\/bolt/i],
  ['replit', /\.replit\.app|replit\.dev|__replco|Made with Replit/i],
  ['v0', /v0\.dev|v0\.app|vusercontent\.net|Generated by v0/i],
];

const DEFAULT_TEMPLATE = /<title>\s*(Vite \+ React|Vite \+ React \+ TS|React App|Lovable App|My Lovable Project)\s*<\/title>|Lovable Generated Project|href="\/vite\.svg"|content="Generated by/i;
const SPA_SHELL = /<div id="root">\s*<\/div>/i;
const VITE_ASSET = /\/assets\/index-[A-Za-z0-9_-]{6,}\.(js|css)/;
const SUPABASE = /[a-z0-9]{20}\.supabase\.co/;
const SHADCN_DEFAULTS = /--radius:\s*0?\.5rem|--primary:\s*222\.2 47\.4% 11\.2%|--primary:\s*262\.1 83\.3% 57\.8%|--ring:\s*222\.2 84% 4\.9%/;
const FRAMER = /framerusercontent\.com|data-framer-name|framer\.website/i;
const WEBFLOW = /data-wf-page|data-wf-site|webflow\.(css|js|com)/i;

function hostOf(url) {
  try {
    return new URL(url).hostname.toLowerCase();
  } catch {
    return '';
  }
}

/**
 * Layer 1: fingerprints from the HTML and its first-party JS/CSS bundles.
 * @returns { builder, builder_evidence[], template_defaults, spa_shell, supabase, shadcn_defaults, framer, webflow }
 */
export async function buildFingerprints(siteUrl, homeHtml, { get = getText, maxAssets = 3 } = {}) {
  const host = hostOf(siteUrl);
  const evidence = [];
  let builder = null;
  for (const [name, re] of BUILDER_HOSTS) {
    if (re.test(host)) {
      builder = name;
      evidence.push(`hosted on ${host}`);
    }
  }

  // Read the first-party bundles: builder artifacts often survive there after the
  // visible branding has been removed.
  const $ = cheerio.load(homeHtml || '');
  const assets = [
    ...$('script[src]').map((_, s) => $(s).attr('src')).get(),
    ...$('link[rel="stylesheet"][href], link[rel="modulepreload"][href]').map((_, l) => $(l).attr('href')).get(),
  ]
    .map((a) => {
      try {
        return new URL(a, siteUrl).href;
      } catch {
        return null;
      }
    })
    .filter((a) => a && hostOf(a) === host)
    .slice(0, maxAssets);
  let code = homeHtml || '';
  for (const a of assets) {
    const r = await get(a);
    if (r.ok) code += '\n' + r.text.slice(0, 2_000_000);
  }

  for (const [name, re] of BUILDER_CODE) {
    const m = code.match(re);
    if (m) {
      builder ||= name;
      evidence.push(`${name}: "${m[0].slice(0, 40)}" in page code`);
    }
  }
  const out = {
    builder,
    builder_evidence: evidence,
    template_defaults: DEFAULT_TEMPLATE.test(homeHtml || ''),
    spa_shell: SPA_SHELL.test(homeHtml || '') && VITE_ASSET.test(homeHtml || ''),
    supabase: SUPABASE.test(code),
    shadcn_defaults: SHADCN_DEFAULTS.test(code),
    framer: FRAMER.test(homeHtml || ''),
    webflow: WEBFLOW.test(homeHtml || ''),
  };
  return out;
}

// Layer 2: runs inside the page (Playwright). Every check is a deterministic DOM or
// computed-style test, so results are explainable in the teardown.
export function slopChecks() {
  const vis = (el) => {
    const r = el.getBoundingClientRect();
    const cs = getComputedStyle(el);
    return r.width > 0 && r.height > 0 && cs.display !== 'none' && cs.visibility !== 'hidden';
  };
  const firstFont = (el) => getComputedStyle(el).fontFamily.split(',')[0].replace(/["']/g, '').trim().toLowerCase();
  const rgb = (s) => (s.match(/[\d.]+/g) || []).map(Number);
  const hue = ([r, g, b]) => {
    r /= 255; g /= 255; b /= 255;
    const max = Math.max(r, g, b), min = Math.min(r, g, b), d = max - min;
    if (!d) return { h: 0, s: 0 };
    let h = max === r ? ((g - b) / d) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
    h = Math.round(h * 60); if (h < 0) h += 360;
    return { h, s: d / (1 - Math.abs(max + min - 1) || 1) };
  };
  const isPurple = (c) => { const v = rgb(c); if (v.length < 3 || (v[3] ?? 1) === 0) return false; const { h, s } = hue(v); return h >= 245 && h <= 290 && s > 0.35; };
  const luminance = (c) => { const [r, g, b] = rgb(c).map((x) => { x /= 255; return x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4; }); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };

  const found = [];
  const h1 = [...document.querySelectorAll('h1')].find(vis);
  const body = document.body;
  const headings = [...document.querySelectorAll('h1,h2,h3')].filter(vis);
  const DEFAULT_FONTS = ['inter', 'geist', 'geist sans', 'space grotesk', 'instrument serif', 'plus jakarta sans', 'dm sans', 'manrope', 'poppins'];

  if (h1 && DEFAULT_FONTS.includes(firstFont(h1)) && DEFAULT_FONTS.includes(firstFont(body))) found.push(`default font everywhere (${firstFont(h1)})`);
  if (headings.some((h) => /text/.test(getComputedStyle(h).backgroundClip || getComputedStyle(h).webkitBackgroundClip || '') && /gradient/.test(getComputedStyle(h).backgroundImage))) found.push('gradient headline text');
  const bgGrad = [...document.querySelectorAll('section, header, main > div, body > div')].slice(0, 12).some((el) => /gradient/.test(getComputedStyle(el).backgroundImage));
  if (bgGrad) found.push('gradient section backgrounds');
  const buttons = [...document.querySelectorAll('a, button')].filter(vis).slice(0, 60);
  if (buttons.some((b) => isPurple(getComputedStyle(b).backgroundColor)) || headings.some((h) => isPurple(getComputedStyle(h).color))) found.push('purple/indigo accent');
  if (h1) {
    const prev = h1.previousElementSibling || h1.parentElement?.previousElementSibling;
    if (prev && vis(prev) && (prev.textContent || '').trim().length < 60 && parseFloat(getComputedStyle(prev).borderRadius) >= 12) found.push('pill badge above the headline');
  }
  const cards = [...document.querySelectorAll('div, li, article')].filter((el) => vis(el) && el.children.length >= 2 && el.children.length <= 5);
  if (cards.some((c) => { const cs = getComputedStyle(c); const w = parseFloat(cs.borderLeftWidth), t = parseFloat(cs.borderTopWidth), r = parseFloat(cs.borderRightWidth); return ((w >= 3 && w > r) || (t >= 3 && t > r)) && cs.borderLeftColor !== cs.borderRightColor; })) found.push('colored left/top card borders');
  if ([...document.querySelectorAll('div, a, button')].filter(vis).slice(0, 400).some((el) => { const s = getComputedStyle(el).boxShadow; return s && s !== 'none' && /rgba?\((?!0, 0, 0)/.test(s) && /\d{2,}px/.test(s); })) found.push('large colored glows');
  if ([...document.querySelectorAll('div, nav, header')].filter(vis).slice(0, 400).some((el) => /blur/.test(getComputedStyle(el).backdropFilter || ''))) found.push('glassmorphism (backdrop blur)');
  if (headings.some((h) => /\p{Extended_Pictographic}/u.test(h.textContent || ''))) found.push('emoji in headings');
  // Three or more sibling cards with the same structure and an icon (svg) first.
  const iconCardRows = [...document.querySelectorAll('div, ul')].filter((p) => {
    const kids = [...p.children].filter(vis);
    if (kids.length < 3 || kids.length > 6) return false;
    const sig = (k) => [...k.children].map((c) => c.tagName).join(',');
    return kids.every((k) => sig(k) === sig(kids[0]) && k.querySelector('svg') && k.querySelector('h3, h4, p'));
  });
  if (iconCardRows.length) found.push('rows of identical icon cards');
  // Effective background: the first non-transparent background up the tree.
  const bgOf = (el) => {
    for (let n = el; n; n = n.parentElement) {
      const c = getComputedStyle(n).backgroundColor;
      if (c && !/rgba?\(0, 0, 0, 0\)|transparent/.test(c)) return c;
    }
    return 'rgb(255, 255, 255)';
  };
  const p = [...document.querySelectorAll('p')].find(vis);
  const bgLum = luminance(p ? bgOf(p) : 'rgb(255, 255, 255)');
  if (bgLum < 0.05 && p) {
    const fg = luminance(getComputedStyle(p).color);
    const ratio = (Math.max(fg, bgLum) + 0.05) / (Math.min(fg, bgLum) + 0.05);
    if (ratio >= 1.5 && ratio < 7) found.push(`dark mode with grey body text (contrast ${ratio.toFixed(1)}:1)`);
  }
  if ([...document.querySelectorAll('h2, h3, span, p')].filter(vis).slice(0, 200).filter((el) => getComputedStyle(el).textTransform === 'uppercase' && (el.textContent || '').length < 40).length >= 4) found.push('all-caps section labels');
  return { patterns: found, fonts: [h1 ? firstFont(h1) : null, firstFont(body)] };
}

// Commercial type foundries (GT, ABC Dinamo, Klim, Pangram, Commercial Type, Apple SF).
const PAID_FONT_RE = /^(gt |abc|söhne|sohne|untitled|tiempos|graphik|founders grotesk|suisse|neue (haas|montreal)|pp |sf ?pro|sfpro|aeonik|circular|apercu|calibre|financier|signifier|lausanne|whyte|favorit)/i;
// Free Google fonts that are not the usual AI defaults: neutral, not a polish signal.
const FREE_FONT_RE = /^(playfair display|jetbrains mono|cairo|open sans|lato|montserrat|nunito|raleway|work sans|outfit|sora|ibm plex|source sans|noto|rubik|karla|lexend|urbanist|figtree|onest|monogram|sans-serif|serif|monospace)/i;
const DEFAULT_FONT_RE = /^(inter|geist|geist sans|space grotesk|instrument serif|plus jakarta sans|dm sans|manrope|poppins|system-ui|-apple-system|arial|helvetica|roboto)$/i;

/**
 * Combine the layers into a verdict.
 * @param fp     buildFingerprints() result
 * @param slop   slopChecks() result or null when no browser pass ran
 * @param lead   the lead (for funding/team/hiring polish signals)
 */
export function vibeVerdict(fp, slop, lead) {
  const reasons = [];
  let score = 0;
  if (fp.builder) {
    score += 60;
    reasons.push(`built with ${fp.builder} (${fp.builder_evidence[0]})`);
  }
  if (fp.template_defaults) { score += 15; reasons.push('untouched Vite/Lovable template defaults'); }
  if (fp.spa_shell) { score += 8; reasons.push('client-only React app shell'); }
  if (fp.supabase) { score += 7; reasons.push('Supabase backend'); }
  if (fp.shadcn_defaults) { score += 8; reasons.push('default shadcn theme values'); }
  // Patterns that polished sites also use (blurred sticky headers, glows, all-caps
  // labels) count little; the ones that mark untouched defaults count more.
  const patterns = slop?.patterns || [];
  const WEAK = /glassmorphism|glows|all-caps|dark mode/;
  const strong = patterns.filter((p) => !WEAK.test(p));
  const patternPoints = strong.length * 7 + (patterns.length - strong.length) * 2;
  if (patterns.length) {
    score += Math.min(30, patternPoints);
    reasons.push(`${patterns.length} default-design patterns: ${[...strong, ...patterns.filter((p) => WEAK.test(p))].slice(0, 4).join(', ')}`);
  }

  const polish = [];
  if (fp.framer) polish.push('Framer marketing site');
  if (fp.webflow) polish.push('Webflow marketing site');
  // Licensed or custom typefaces cost money and a designer's decision.
  const fonts = (slop?.fonts || []).filter(Boolean);
  const paidFont = fonts.find((f) => PAID_FONT_RE.test(f));
  const customFont = paidFont || fonts.find((f) => !DEFAULT_FONT_RE.test(f) && !FREE_FONT_RE.test(f));
  if (customFont) polish.push(`${paidFont ? 'licensed' : 'custom'} typeface (${customFont})`);
  if (lead.hiring?.design_roles?.length) polish.push('hiring designers');
  if ((lead.yc?.team_size || 0) >= 15) polish.push(`team of ${lead.yc.team_size}`);
  if (lead.yc?.stage === 'Growth') polish.push('growth-stage');
  score -= polish.length * 12;

  score = Math.max(0, Math.min(100, score));
  const verdict = fp.builder || score >= 45
    ? 'vibe-coded'
    : score >= 25
      ? 'likely vibe-coded'
      : polish.length >= 2 || paidFont || fp.framer || fp.webflow
        ? 'polished'
        : 'unclear';
  return { vibe_score: score, verdict, reasons, polish_signals: polish, design_patterns: patterns };
}
